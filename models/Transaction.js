const mongoose = require("mongoose");

const transactionSchema = new mongoose.Schema(
  {
    // --------------------------------------------------------
    // REGISTRATION NUMBER
    // --------------------------------------------------------

    regNo: {
      type: String,
     
      trim: true,
    },

    // --------------------------------------------------------
    // NAME
    // --------------------------------------------------------

    name: {
      type: String,
  
      trim: true,
    },

    // --------------------------------------------------------
    // DATE
    // --------------------------------------------------------

    date: {
      type: Date,
    
    },

    // --------------------------------------------------------
    // CASH / ONLINE
    // --------------------------------------------------------

    type: {
      type: String,
      enum: ["Cash", "Online"],
   
    },

    // --------------------------------------------------------
    // AMOUNT
    // --------------------------------------------------------

    amount: {
      type: Number,
      
      min: 0,
    },

    // --------------------------------------------------------
    // STATUS
    // --------------------------------------------------------

    status: {
      type: String,
      enum: ["Pending", "Done"],
      
    },

    // --------------------------------------------------------
    // JAMA / KHARCH
    // --------------------------------------------------------

    transactionType: {
      type: String,
      enum: ["jama", "kharch"],
    
    },
  },
  {
    timestamps: true,
  }
);

// ============================================================
// INDEX
// ============================================================

transactionSchema.index({
  transactionType: 1,
  regNo: 1,
});

transactionSchema.index({
  transactionType: 1,
  date: -1,
});

module.exports = mongoose.model(
  "Transaction",
  transactionSchema
);